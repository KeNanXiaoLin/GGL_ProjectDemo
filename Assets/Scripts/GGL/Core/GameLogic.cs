using System;
using System.Collections;
using System.Collections.Generic;
using KNXL;
using KNXL.AutoGenerated.Data;
using KNXL.AutoGenerated.UI;
using UnityEngine;
using UnityEngine.Rendering;

public class GameLogic : MonoBehaviour
{
    /// <summary>
    /// 当前处于什么世界
    /// </summary>
    private E_World currentWorld;
    public Volume volume;
    /// <summary>
    /// 当前世界所有可以被附身的东西的行为
    /// </summary>
    public List<BaseAction> actions = new List<BaseAction>();
    
    private MapGenerate mapGenerate;

    void Start()
    {
        MusicMgr.Instance.PlayBKMusic("游玩界面");
        currentWorld = E_World.Out_World;
        GameManager.Instance.CurrentWorldType = currentWorld;
        EventCenter.Instance.EventTrigger<E_World>(E_EventType.E_WorldChange, currentWorld);
        
        // 获取MapGenerate组件
        mapGenerate = GetComponent<MapGenerate>();
        
        // 生成当前关卡
        GenerateLevel(GameManager.Instance.CurrentLevel);
    }

    /// <summary>
    /// 生成指定关卡
    /// </summary>
    /// <param name="levelID">关卡ID</param>
    public void GenerateLevel(int levelID)
    {
        if (mapGenerate != null)
        {
            StartCoroutine(mapGenerate.GenerateLevel(levelID));
        }
        else
        {
            Debug.LogError("GenerateLevel: mapGenerate is null");
        }
        GameManager.Instance.InitPlayer();
    }

    public void InitActions()
    {
        actions.Clear();
        BaseAction[] tempActions = GameObject.FindObjectsOfType<BaseAction>();
        foreach (var item in tempActions)
        {
            if(!item.data.isDecorator)
            {
                actions.Add(item);
            }
        }
    }

    // Update is called once per frame
    void Update()
    {
        if (Input.GetKeyDown(KeyCode.Space))
        {
            ChangeWorld();
        }
    }

    private void ChangeWorld()
    {
        switch (currentWorld)
        {
            case E_World.In_World:
                Debug.Log("进入外世界");
                currentWorld = E_World.Out_World;
                GameManager.Instance.CurrentWorldType = currentWorld;
                // UIMgr.Instance.HidePanel<GrayPanel>();
                volume.gameObject.SetActive(false);
                EventCenter.Instance.EventTrigger<E_World>(E_EventType.E_WorldChange, currentWorld);
                break;
            case E_World.Out_World:
                Debug.Log("进入里世界");
                currentWorld = E_World.In_World;
                GameManager.Instance.CurrentWorldType = currentWorld;
                // UIMgr.Instance.ShowPanel<GrayPanel>();
                volume.gameObject.SetActive(true);
                EventCenter.Instance.EventTrigger<E_World>(E_EventType.E_WorldChange, currentWorld);
                break;

        }
    }
}
