using System;
using KNXL;
using KNXL.AutoGenerated.Data;
using UnityEngine;

public class Player : MonoBehaviour
{
    [SerializeField] private int nowCrazyValue = 5;
    [SerializeField] private SpriteRenderer spriteRenderer;
    [SerializeField] private SpriteRenderer soulSR;
    /// <summary>
    /// 玩家持有的面具数据，宿主
    /// </summary>
    private CfgMaskData selfMaskData;

    public int NowCrazyValue { get => nowCrazyValue; }

    private void Start()
    {
        selfMaskData = ConfigManager.Instance.GetData<CfgMaskData>(10007);
        ResLoadMgr.Instance.LoadRes<Sprite>(selfMaskData.resIdNoMask, (sprite) =>
        {
            spriteRenderer.sprite = sprite;
        });
        nowCrazyValue = selfMaskData.startCrazy;
        EventCenter.Instance.EventTrigger<int>(E_EventType.E_UpdateGameUI, nowCrazyValue);
    }

    void OnEnable()
    {
        EventCenter.Instance.AddEventListener<E_World>(E_EventType.E_WorldChange, ShowSelfSoul);
    }

    void OnDisable()
    {
        EventCenter.Instance.RemoveEventListener<E_World>(E_EventType.E_WorldChange, ShowSelfSoul);
    }

    private void ShowSelfSoul(E_World curWorld)
    {
        switch (curWorld)
        {
            case E_World.In_World:
                ResLoadMgr.Instance.LoadRes<Sprite>(selfMaskData.resSoul, (sprite) =>
                {
                    Debug.Log("加载灵魂成功" + selfMaskData.resSoul);
                    soulSR.sprite = sprite;
                });
                break;
            case E_World.Out_World:
                soulSR.sprite = null;
                break;
        }
    }
}